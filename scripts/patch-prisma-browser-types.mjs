/**
 * After `prisma generate`, ensure browser-safe enum imports resolve in webpack
 * and have full TypeScript types.
 *
 * Prisma emits `enums.ts` as `export * from "./index-browser"` but:
 * 1. Does not emit `enums.js` — webpack (via package.json exports) fails to
 *    resolve `@/generated/prisma/enums` during `next build`.
 * 2. Does not emit `index-browser.d.ts` — TS then treats enum members as string.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const prismaDir = path.join(root, "src/generated/prisma");

fs.mkdirSync(prismaDir, { recursive: true });

const indexBrowserDts = path.join(prismaDir, "index-browser.d.ts");
fs.writeFileSync(
  indexBrowserDts,
  `/**
 * Type declarations for the browser-safe Prisma entry.
 *
 * \`enums.ts\` re-exports from \`./index-browser\`. Without this file, TypeScript
 * resolves only the .js runtime (allowJs) and treats enum members as \`string\`,
 * and enum identifiers as values-only (TS2749 when used as types).
 *
 * Regenerated by scripts/patch-prisma-browser-types.mjs after prisma generate.
 */
export * from "./index";
`,
  "utf8"
);
console.log(`[patch-prisma-browser-types] wrote ${path.relative(root, indexBrowserDts)}`);

// Webpack resolves package subpaths to .js, not .ts — emit a CJS shim.
const enumsJs = path.join(prismaDir, "enums.js");
fs.writeFileSync(
  enumsJs,
  `/* Generated by scripts/patch-prisma-browser-types.mjs after prisma generate. */
module.exports = require("./index-browser.js");
`,
  "utf8"
);
console.log(`[patch-prisma-browser-types] wrote ${path.relative(root, enumsJs)}`);
